"""File discovery for lgrep.

Walks directory trees and identifies files to index, respecting
.gitignore and .lgrepignore patterns.

Security exclusions:
- Path traversal validation (files outside root are rejected)
- Symlink escape detection (symlinks pointing outside root are rejected)
- Secret file detection (.env, .pem, credentials.*, etc.)
- Binary file sniffing (null-byte detection)
- Per-file size cap (default 1 MB)
- Skip patterns for common build/dependency directories
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import TYPE_CHECKING

import structlog
from pathspec import GitIgnoreSpec

if TYPE_CHECKING:
    from collections.abc import Iterator

    from pathspec import RegexPattern

log = structlog.get_logger()

DEFAULT_LGREPIGNORE_TEMPLATE = """# lgrep recommended ignore patterns
# Generated by `lgrep init-ignore`. Edit as needed.

# Dependencies
node_modules/
vendor/
venv/
.venv/

# Build artifacts
dist/
build/
target/
out/
.next/
.nuxt/

# Caches
__pycache__/
.pytest_cache/
.mypy_cache/
.ruff_cache/
.tox/
coverage/

# Common generated outputs
src/generated/
docs/site/

# Large fixtures/snapshots
*.snap
*.test.data

# ADV change/archive state (stale planning text)
.adv/changes/
.adv/archive/
"""

# Maximum file size to index (1 MB). Files larger than this are skipped.
MAX_FILE_SIZE_BYTES = 1 * 1024 * 1024  # 1 MB

# Directories to always skip (build artifacts, dependencies, generated code).
_SKIP_DIRS: frozenset[str] = frozenset(
    [
        ".git",
        ".hg",
        ".svn",
        "node_modules",
        "vendor",
        "dist",
        "build",
        "__pycache__",
        ".pytest_cache",
        ".mypy_cache",
        ".ruff_cache",
        ".tox",
        "venv",
        ".venv",
        "env",
        ".env",
        "site-packages",
        ".eggs",
        "*.egg-info",
        "target",  # Rust/Java build output
        "out",
        ".next",
        ".nuxt",
        "coverage",
        ".coverage",
    ]
)

# Secret file patterns — exact filenames or glob-style suffixes.
# These files are excluded regardless of gitignore rules.
_SECRET_FILENAMES: frozenset[str] = frozenset(
    [
        ".env",
        ".env.local",
        ".env.development",
        ".env.production",
        ".env.test",
        ".env.staging",
        "credentials.json",
        "service-account.json",
        "service_account.json",
        "secrets.json",
        "secrets.yaml",
        "secrets.yml",
        ".netrc",
        ".npmrc",
        ".pypirc",
        "id_rsa",
        "id_ed25519",
        "id_ecdsa",
        "id_dsa",
    ]
)

# Secret file suffixes (checked against the full filename).
_SECRET_SUFFIXES: tuple[str, ...] = (
    ".pem",
    ".key",
    ".p12",
    ".pfx",
    ".crt",
    ".cer",
    ".der",
    ".jks",
    ".keystore",
)

# Prefix patterns for secret files.
_SECRET_PREFIXES: tuple[str, ...] = (
    ".env.",
    "credentials.",
)


def _is_secret_file(path: Path) -> bool:
    """Return True if the file looks like it contains secrets."""
    name = path.name
    # Exact filename match
    if name in _SECRET_FILENAMES:
        return True
    # Suffix match
    if name.endswith(_SECRET_SUFFIXES):
        return True
    # Prefix match
    return bool(any(name.startswith(prefix) for prefix in _SECRET_PREFIXES))


def _is_binary_file(path: Path) -> bool:
    """Return True if the file appears to be binary (contains null bytes).

    Reads only the first 8 KB to keep this fast.
    """
    try:
        with path.open("rb") as f:
            chunk = f.read(8192)
        return b"\x00" in chunk
    except OSError:
        return True  # Unreadable files are treated as binary


def _is_oversized(path: Path) -> bool:
    """Return True if the file exceeds MAX_FILE_SIZE_BYTES."""
    try:
        return path.stat().st_size > MAX_FILE_SIZE_BYTES
    except OSError:
        return True  # Unreadable files are excluded


def _resolves_outside_root(path: Path, root: Path) -> bool:
    """Return True if the path (after resolving symlinks) is outside root."""
    try:
        resolved = path.resolve()
        resolved.relative_to(root)
        return False
    except ValueError:
        return True


def scaffold_lgrepignore(root_path: str | Path, force: bool = False) -> tuple[Path, bool]:
    """Create a default .lgrepignore file in the project root.

    Args:
        root_path: Project root directory
        force: Overwrite existing file if True

    Returns:
        Tuple of (path_to_file, created_or_overwritten)
    """
    root = Path(root_path).resolve()
    lgrepignore_path = root / ".lgrepignore"

    if lgrepignore_path.exists() and not force:
        return lgrepignore_path, False

    lgrepignore_path.write_text(DEFAULT_LGREPIGNORE_TEMPLATE)
    return lgrepignore_path, True


class _IgnoreFile:
    """Exclusion rules from one root ignore file, evaluated the way git evaluates them.

    pathspec compiles the patterns; this class applies them. The last pattern
    that matches a path itself decides it, so ``gen/**`` matches the contents
    of ``gen`` but not ``gen``. A directory below an excluded directory stays
    excluded. A file with no pattern of its own takes its directory's decision;
    a file pattern still decides a file inside an excluded directory, which
    ``find_files`` never visits because it prunes that directory.

    For directories, directory-only patterns drop their trailing ``/`` so they
    match the directory path itself.
    """

    def __init__(self, path: Path) -> None:
        file_lines: list[str] = []
        dir_lines: list[str] = []
        for number, line in enumerate(path.read_text().splitlines(), start=1):
            dir_line = _directory_form(line)
            try:
                GitIgnoreSpec.from_lines([line, dir_line])
            except ValueError as exc:
                # Git skips invalid patterns, such as a lone "!".
                log.warning("ignore_pattern_skipped", path=str(path), line=number, error=str(exc))
                continue
            file_lines.append(line)
            dir_lines.append(dir_line)
        self._file_patterns = _compile(file_lines)
        self._dir_patterns = _compile(dir_lines)
        self._excluded_dirs: dict[str, bool] = {}

    def excludes(self, rel_path: str, is_dir: bool) -> bool:
        """Return whether a root-relative POSIX path is excluded."""
        parent = rel_path.rpartition("/")[0]
        if not is_dir:
            own = _last_match(self._file_patterns, rel_path)
            if own is not None:
                return own
            return bool(parent) and self.excludes(parent, is_dir=True)
        excluded = self._excluded_dirs.get(rel_path)
        if excluded is None:
            excluded = (bool(parent) and self.excludes(parent, is_dir=True)) or bool(
                _last_match(self._dir_patterns, rel_path)
            )
            self._excluded_dirs[rel_path] = excluded
        return excluded


def _compile(lines: list[str]) -> list[RegexPattern]:
    return [p for p in GitIgnoreSpec.from_lines(lines).patterns if p.include is not None]


def _directory_form(line: str) -> str:
    """Return the pattern with its directory-only ``/`` removed."""
    if line.endswith("\\ "):
        return line
    stripped = line.rstrip(" ")
    if stripped.endswith("/") and stripped.lstrip("!") != "/":
        return stripped[:-1]
    return line


def _last_match(patterns: list[RegexPattern], rel_path: str) -> bool | None:
    """Return the decision of the last pattern matching the path itself, if any.

    pathspec sets the ``ps_d`` group when a pattern matches through a leading
    directory; those matches belong to an ancestor and are skipped here.
    """
    decision = None
    for pattern in patterns:
        result = pattern.match_file(rel_path)
        if result is not None and result.match.groupdict().get("ps_d") is None:
            decision = bool(pattern.include)
    return decision


class FileDiscovery:
    """Discovers files in a project directory while respecting ignore patterns.

    Combines .gitignore and .lgrepignore rules with security-aware filtering:
    - Rejects paths outside the project root (path traversal protection)
    - Rejects symlinks that escape the root
    - Rejects secret files (.env, .pem, credentials.*, etc.)
    - Rejects binary files (null-byte detection)
    - Rejects oversized files (> 1 MB)
    - Skips common build/dependency directories (node_modules, vendor, dist, etc.)
    """

    def __init__(self, root_path: str | Path) -> None:
        """Initialize file discovery.

        Args:
            root_path: Absolute path to the project root directory
        """
        self.root_path = Path(root_path).resolve()

        self._ignore_files: list[_IgnoreFile] = []
        for name in (".gitignore", ".lgrepignore"):
            ignore_path = self.root_path / name
            if ignore_path.exists():
                self._ignore_files.append(_IgnoreFile(ignore_path))
                log.debug("ignore_file_loaded", path=str(ignore_path))

        log.info("file_discovery_initialized", root=str(self.root_path))

    def is_ignored(self, path: str | Path) -> bool:
        """Check if a path is ignored by any rules.

        Applies security checks first (path traversal, symlinks, secrets,
        binary, size), then gitignore/lgrepignore rules.

        Args:
            path: Absolute or relative path to check

        Returns:
            True if the path should be ignored
        """
        path = Path(path)

        # Resolve to absolute for security checks — always resolve to eliminate
        # any .. components that could escape the root.
        abs_path = (self.root_path / path).resolve() if not path.is_absolute() else path.resolve()

        # 1. Path traversal: reject anything outside root
        try:
            abs_path.relative_to(self.root_path)
        except ValueError:
            log.debug("security_path_traversal_rejected", path=str(path))
            return True

        # 2. Symlink escape: reject symlinks that resolve outside root
        if abs_path.is_symlink() and _resolves_outside_root(abs_path, self.root_path):
            log.debug("security_symlink_escape_rejected", path=str(path))
            return True

        # 3. Secret file detection
        if _is_secret_file(abs_path):
            log.debug("security_secret_file_rejected", path=str(path))
            return True

        # 4. Skip directory names
        if abs_path.is_dir():
            if abs_path.name in _SKIP_DIRS:
                return True
        else:
            # Check if any parent directory is in the skip list
            try:
                rel = abs_path.relative_to(self.root_path)
                if any(part in _SKIP_DIRS for part in rel.parts[:-1]):
                    return True
            except ValueError:
                return True

        # 5. Binary file detection (only for files, not dirs)
        if abs_path.is_file() and not abs_path.is_symlink():
            if _is_binary_file(abs_path):
                log.debug("security_binary_file_rejected", path=str(path))
                return True

            # 6. File size cap
            if _is_oversized(abs_path):
                log.debug("security_oversized_file_rejected", path=str(path))
                return True

        # 7. Gitignore rules
        rel_path = abs_path.relative_to(self.root_path).as_posix()
        is_dir = abs_path.is_dir()
        if any(ignore_file.excludes(rel_path, is_dir) for ignore_file in self._ignore_files):
            return True

        # 8. Legacy: always ignore .git directory parts
        try:
            rel = abs_path.relative_to(self.root_path)
            if ".git" in rel.parts:
                return True
        except ValueError:
            return True

        return False

    def find_files(self) -> Iterator[Path]:
        """Iterate over all non-ignored files in the project.

        Yields:
            Absolute paths to discovered files
        """
        for root, dirs, files in os.walk(self.root_path, followlinks=False):
            root_path = Path(root)

            # Filter directories in-place to prevent os.walk from entering them
            orig_dirs = list(dirs)
            dirs[:] = [d for d in dirs if not self.is_ignored(root_path / d)]

            if len(dirs) < len(orig_dirs):
                ignored = set(orig_dirs) - set(dirs)
                log.debug("skipping_directories", root=str(root_path), ignored=list(ignored))

            for file in files:
                file_path = root_path / file
                if not self.is_ignored(file_path):
                    yield file_path
                else:
                    log.debug("skipping_file", path=str(file_path))
